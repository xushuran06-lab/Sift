const assert=require('node:assert/strict');
const B=require('./dist/content-core.js');
assert.equal(B.cleanUrl('javascript:alert(1)'),null);
assert.equal(B.cleanUrl('https://name:secret@example.com'),null);
assert.equal(B.cleanUrl('https://example.com/a?utm_source=demo&keep=1#part'),'https://example.com/a?keep=1');
assert.equal(B.platform('https://mp.weixin.qq.com/s/demo'),'微信公众号');
assert.equal(B.platform('https://www.bilibili.com/video/demo'),'哔哩哔哩');
assert.equal(B.platform('https://bilibili.com.evil.example/a'),'bilibili.com.evil.example');
assert.equal(B.validate({title:'空笔记'}).error,'请添加链接、笔记正文或图片。');
const note=B.validate({title:'AI 应用学习',text:'先写测试，再做功能。',tags:'AI、AI,学习'}).value;
assert.equal(note.category,'tech');assert.deepEqual(note.tags,['AI','学习']);assert.equal(note.summary,'先写测试，再做功能。');
const link=B.validate({title:'文章',url:'https://example.com'}).value;
assert.equal(link.status,'link-only');assert.match(link.summary,/尚未抓取/);
const rows=[{...note,id:'1',collections:['c'],watch:true,deleted:false},{...link,id:'2',collections:[],watch:false,deleted:true}];
assert.equal(B.search(rows,{query:'测试'}).length,1);
assert.equal(B.search(rows,{collection:'c',watch:true}).length,1);
assert.equal(B.search(rows,{trash:true})[0].id,'2');
const old={items:[{id:'campus'}],prefs:{types:['volunteer']}};
B.migrate(old,rows);assert.equal(old.items[0].id,'campus');assert.equal(old.brain.items.length,2);
B.migrate(old,[]);assert.equal(old.brain.items.length,2);
console.log('PASS: safe URL handling, platform identification, honest link-only state, note extraction, filtering and non-destructive migration.');
