const assert=require('node:assert/strict');
const C=require('./dist/core.js');
const msg='【图书馆志愿招募】\n活动时间：11月7日14:00—17:00\n地点：校图书馆\n志愿时长：3小时\n报名截止：11月3日20:00';
const a={...C.analyze(msg),id:'one',sources:['volunteer']};
assert.equal(a.deadline,'2026-11-03T12:00:00.000Z');
assert.equal(C.hoursUntil(a.deadline),4);
assert.equal(a.type,'volunteer');
assert.equal(a.location,'校图书馆');
assert.equal(a.duration,'3 小时');
assert.equal(C.analyze('【志愿活动】地点待定，时间另行通知').deadline,null);
assert.equal(C.analyze('【志愿活动】报名截止：2月30日20:00').deadline,null);
assert.equal(C.analyze('【志愿活动】报名截止：11月3日25:00').deadline,null);
assert.equal(C.analyze('【志愿活动】报名截止：11月3日').deadline,null);
assert.equal(C.analyze('晚上吃什么？').kind,'noise');
assert.equal(C.analyze(' ').kind,'empty');
const duplicate=C.ingest([a],{...a,id:'two',sources:['college']});
assert.equal(duplicate.kind,'duplicate');assert.equal(duplicate.items.length,1);assert.deepEqual(duplicate.items[0].sources,['volunteer','college']);
const update=C.ingest(duplicate.items,{...C.analyze('【图书馆志愿招募】更新：名额已满'),id:'three',sources:['volunteer']});
assert.equal(update.kind,'updated');assert.equal(update.item.id,'one');assert.equal(update.item.status,'cancelled');assert.equal(update.item.history.length,1);
assert.equal(C.matches(a,{types:['research']}),false);
assert.equal(C.matches(a,{types:['volunteer']}),true);
console.log('PASS: date extraction, invalid and incomplete dates, noise filtering, cross-source deduplication, state updates and preference matching.');
