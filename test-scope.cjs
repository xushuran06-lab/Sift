const assert=require('node:assert/strict');
const S=require('./dist/scope-core.js');
const sources=[{id:'a'},{id:'b'}];
const legacy={enabled:['a','b'],brain:{items:[{id:'saved'}]}};
S.migrate(legacy,sources);assert.deepEqual(legacy.enabled,[]);assert.equal(legacy.brain.items[0].id,'saved');
const selected={enabled:['a']};S.migrate(selected,sources);assert.deepEqual(selected.enabled,['a']);
let calls=0;const analyzer=()=>{calls++;return {kind:'noise'};};
assert.equal(S.process(selected,sources,'b','private text',analyzer).kind,'blocked');
assert.equal(S.process({...selected,enabled:['unknown']},sources,'unknown','text',analyzer).kind,'blocked');
assert.equal(calls,0,'Rejected sources never invoke the analyzer');
selected.sourceModes.a='summary';
const result=S.process(selected,sources,'a','Title\nFirst\nFirst\nSecond',analyzer);
assert.equal(calls,0,'Summary-only sources never invoke opportunity analyzer');
assert.equal(result.summary.summary,'Title；First；Second');assert.equal(result.opportunity,null);
selected.sourceModes.a='opportunities';const opportunity=S.process(selected,sources,'a','text',analyzer);
assert.equal(calls,1);assert.equal(opportunity.summary,null);
selected.sourceModes.a='both';assert.ok(S.process(selected,sources,'a','text',analyzer).summary);assert.equal(calls,2);
assert.equal(S.process(selected,sources,'a',' ',analyzer).kind,'empty');assert.equal(calls,2);
selected.enabled=[];assert.equal(S.process(selected,sources,'a','text',analyzer).kind,'blocked');assert.equal(calls,2);
console.log('PASS: whitelist before analysis, no unknown-source ingestion, independent modes, extractive summary deduplication, non-destructive migration.');
