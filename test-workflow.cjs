const assert=require('node:assert/strict');
const W=require('./dist/workflow-core.js'),C=require('./dist/core.js');
const now=new Date('2026-11-05T16:30:00+08:00');
const item=W.extract('【线性代数作业】\n提交截止：明天20:00\n面向：大一学生\n提交方式：教学平台上传PDF',C.analyze,now);
assert.equal(item.type,'homework');assert.equal(item.deadline,'2026-11-06T12:00:00.000Z');assert.equal(item.actionText,'教学平台上传PDF');
assert.equal(W.extract('【校园事务】领取：校园卡\n截止：2027年1月3日10:00',C.analyze,now).deadline,'2027-01-03T02:00:00.000Z');
const dateOnly=W.extract('【志愿活动】\n报名截止：11月9日',C.analyze,now);
assert.equal(dateOnly.deadline,null);assert.equal(dateOnly.deadlineDay,'2026-11-09');
assert.throws(()=>W.calendar(dateOnly,now),/补全/);
for(const text of ['2026-02-30T12:00','11月9日25:00','11月9日20:61'])assert.equal(W.dateValue(text,now).iso,null);
assert.equal(W.dateValue('后天18:00',now).iso,'2026-11-07T10:00:00.000Z');
assert.equal(W.dateValue('2026-12-31T23:30',now).date,'2026-12-31');
assert.equal(W.dateValue('明天10:00','2026-12-31T23:30:00+08:00').iso,'2027-01-01T02:00:00.000Z');
assert.equal(W.relevance(item,{grade:'大二'}).match,false);
assert.equal(W.relevance(item,{grade:'大一',include:'线性代数、Python'}).match,true);
assert.equal(W.relevance(item,{include:'Python'}).match,false);
assert.equal(W.relevance(item,{exclude:'作业'}).match,false);
assert.equal(W.relevance({...item,eligibility:'面向大一至大四学生'},{grade:'大二'}).match,true);
assert.equal(W.relevance({...item,eligibility:'待确认'},{grade:'大三'}).match,true,'Unknown eligibility is shown for review, not invented');
assert.equal(W.ended(item,now),false);assert.equal(W.ended(item,'2026-11-07'),true);
assert.throws(()=>W.calendar({...item,status:'cancelled'},now),/取消/);
const calendar=W.calendar({...item,id:'safe-id',title:'中文标题'.repeat(30)+'\nBEGIN:VEVENT',raw:'第一行\n第二行;测试,逗号'},now);
assert.match(calendar,/DTSTART:20261106T120000Z/);assert.match(calendar,/TRIGGER:-PT1H/);
assert.equal(calendar.split('\r\n').filter(x=>x==='BEGIN:VEVENT').length,1);
for(const line of calendar.split('\r\n'))assert.ok(Buffer.byteLength(line)<=75,'Calendar folds UTF-8 by bytes');
assert.match(calendar.replace(/\r\n /g,''),/\\nBEGIN:VEVENT/);
console.log('PASS: homework extraction, current-year and relative dates, invalid dates, unknown precision, grade/keyword filters, expiry and safe UTF-8 calendar export.');
